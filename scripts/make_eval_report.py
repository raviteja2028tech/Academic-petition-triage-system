"""Builds docs/EVALUATION_REPORT.md from the stored evaluation result files. Nothing is typed by hand: every number and every row
comes from eval/results/*.json and eval/scenarios.json. Re-run after any evaluation:  python scripts/make_eval_report.py"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
R = os.path.join(ROOT, "eval", "results")
RUNS = [  # (file, title, note)
    ("real_v1.json", "Run A - real LLM `openai/gpt-oss-120b`, research prompt v1", "First complete attempt of all 19 scenarios. S27/S28 ended `llm_unavailable` (provider rate limiting during the run)."),
    ("real_qwen_v1.json", "Run B - real LLM `qwen/qwen3.8-27b`, research prompt v1", "Full re-run of all 19 scenarios on a second model of the same provider, because `gpt-oss-120b`'s daily token quota (200,000) was exhausted."),
    ("real_qwen_v2_subset.json", "Run C - real LLM `qwen/qwen3.8-27b`, research prompt v2 (3-scenario subset)", "Prompt comparison on the scenarios where retrieval was weakest. Quota-limited: not a full evaluation."),
    ("scripted_hash.json", "Run D - scripted model (28 scenarios)", "Tests the safety machinery (verification, guardrails, escalation, degradation) under specified model behaviour. NOT a measure of any LLM."),
]


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p, encoding="utf8")) if os.path.isfile(p) else None


def exp_str(e: dict) -> str:
    return f"{e['status']}/{e.get('route') or '*'}" + (f"/{e['escalation_reason']}" if e.get("escalation_reason") else "")


def act_str(r: dict) -> str:
    return f"{r['status']}/{r.get('route') or '-'}" + (f"/{r['escalation_reason']}" if r.get("escalation_reason") else "")


def cell(s: str, n: int = 170) -> str:
    s = " ".join(str(s or "").split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def fmt(v):
    return "n/a" if v is None else f"{v:.3f}"


def main() -> int:
    sc = {s["id"]: s for s in json.load(open(os.path.join(ROOT, "eval", "scenarios.json"), encoding="utf8"))["scenarios"]}
    L = ["# Evaluation report", "", "_Generated by `scripts/make_eval_report.py` from `eval/results/*.json`. Do not edit by hand._", "",
         "## How to read this", "",
         "* **Expected** outcomes are the team's reading of the verified corpus (`eval/scenarios.json`); scenarios marked *interp.* depend on the open "
         "interpretations in `KNOWN_LIMITATIONS.md` §A (e.g. what \"10 %\" means), so a pass is technical conformance, not proof of regulatory correctness.",
         "* A **FAIL** means the observed outcome differs from the expectation on at least one of: status, route, escalation reason, whether the LLM was called, "
         "citation groundedness, or gold-clause retrieval recall. Expected values were **not** changed to make results pass.",
         "* Each real run is **one sample per scenario** (n = 19). Differences of a scenario or two are not statistically meaningful, and the same model can answer "
         "differently on another day.", "", "## Runs", "", "| Run | Model | Prompt | Scenarios | Task success | Generated |", "|---|---|---|---|---|---|"]
    loaded = [(f, t, n, load(f)) for f, t, n in RUNS]
    for f, t, n, d in loaded:
        if d:
            m = d["metrics"]["task_success_rate"]
            ok = sum(1 for r in d["scenarios"] if r["task_success"])
            L.append(f"| {t.split(' - ')[0]} (`{f}`) | {d['meta']['model']} | {d['meta']['research_prompt_version']} | {d['meta']['scenario_count']} | {ok}/{len(d['scenarios'])} ({m['value']:.3f}) | {d['meta']['generated_at'][:16].replace('T', ' ')} UTC |")
        else:
            L.append(f"| {t.split(' - ')[0]} (`{f}`) | — | — | — | not available | — |")
    L += ["", "**Provider blocker found during this work:** the configured provider enforces a **daily** token quota of 200,000 on `gpt-oss-120b` "
          "(plus 8,000 tokens/minute). A full agent run costs 13k-23k tokens, so a 19-scenario evaluation does not fit in one day on that model. A re-run of the failed "
          "gpt-oss scenarios after the quota was spent returned HTTP 429 (\"tokens per day (TPD): Limit 200000, Used 199459 ... try again in 7m46s\") for every call "
          "and is therefore **not** reported as a result; the client now fails fast on such quota errors instead of waiting.", ""]
    for f, t, note, d in loaded:
        L += [f"## {t}", "", note, ""]
        if not d:
            L += ["_Result file not present._", ""]
            continue
        L += ["### Metrics", "", "| Metric | Value | n |", "|---|---|---|"]
        for k, v in d["metrics"].items():
            L.append(f"| {k.replace('_', ' ')} | {fmt(v['value'])} | {v['n']} |")
        j = d.get("llm_judge") or {}
        if j.get("enabled"):
            L += ["", f"LLM-judge scores (separate; the judge is itself an LLM): " + ", ".join(f"{k} {fmt(j[k]['value'])} (n={j[k]['n']})" for k in ("context_relevance", "groundedness", "faithfulness") if k in j) + f"; judge failures: {j.get('runs_failed')}."]
        L += ["", "### Scenarios", "", "| Scenario | Expected | Actual | Result | Explanation (from the run) | Evidence (verified citations / retrieved) |", "|---|---|---|---|---|---|"]
        for r in d["scenarios"]:
            s = sc.get(r["id"], {})
            e = s.get("expected", {})
            why = r.get("escalation_detail") or r.get("position") or ""
            if not why and r.get("escalation_reason") == "llm_unavailable":
                why = "Provider rate limiting / quota ended the run before a recommendation (no determination, safely escalated)."
            if not r["task_success"]:
                bits = [k for k, ok in (("status", r.get("status_ok")), ("route", r.get("route_ok")), ("escalation", r.get("escalation_ok")), ("llm-called", r.get("llm_called_ok"))) if ok is False]
                if r.get("gold_recall") is not None and r["gold_recall"] < 1:
                    bits.append(f"gold recall {r['gold_recall']:.2f}")
                if r.get("attempted_hallucination"):
                    bits.append("verifier rejected a model citation once")
                why = (f"**Differs on: {', '.join(bits) or 'see metrics'}.** " + why)
            ev = ", ".join(r.get("citations") or []) or "none"
            ret = ", ".join(r.get("retrieved_clauses") or [])
            L.append(f"| {r['id']}{' *interp.*' if s.get('interpretation_dependent') else ''} | {exp_str(e)} | {act_str(r)} | {'PASS' if r['task_success'] else '**FAIL**'} | {cell(why)} | cited: {ev}; retrieved: {cell(ret, 90) or 'none'} |")
        L.append("")
    a, b, c = (x[3] for x in loaded[:3])
    if b and c:
        L += ["## Prompt comparison (research v1 vs v2) - same model, 3 scenarios", "", "| Scenario | v1 outcome | v1 gold recall | v1 retrieved | v2 outcome | v2 gold recall | v2 retrieved |", "|---|---|---|---|---|---|---|"]
        b1 = {r["id"]: r for r in b["scenarios"]}
        for r in c["scenarios"]:
            o = b1.get(r["id"])
            if o:
                L.append(f"| {r['id']} | {act_str(o)} | {fmt(o.get('gold_recall'))} | {len(o.get('retrieved_clauses', []))} clauses | {act_str(r)} | {fmt(r.get('gold_recall'))} | {len(r.get('retrieved_clauses', []))} clauses |")
        L += ["", "Three scenarios, one sample each: this shows the direction, not a significant difference.", ""]
    L += ["## Known limitations of this evaluation", "",
          "* One sample per scenario, two different real models, no human-labelled gold set; regulatory expectations rest on unconfirmed interpretations.",
          "* Runs A and B were not made with identical code: between them the verifier gained a guard that blocks AI *rejections* inside the discretionary band "
          "(motivated by Run A's S06/S07, where the model rejected 80 % / 84 % petitions) and the client gained pacing/quota handling. Run B's models did not reject those "
          "petitions, so the guard is **verified by unit tests (`test_model_reject_inside_the_condonable_band_is_converted_to_referral`) and scripted scenarios, not by a real-model run**.",
          "* The v1-vs-v2 prompt comparison covers 3 scenarios on one model; the quota prevented more.",
          "* The retrieval metrics count clauses, not passages, and gold clauses are limited to the four verified ones (`docs/corpus_verification.md`).",
          "* LLM-judge scores exist only where the judge call fit the quota (Run A); the judge is an LLM and is not ground truth.", ""]
    out = os.path.join(ROOT, "docs", "EVALUATION_REPORT.md")
    open(out, "w", encoding="utf8", newline="\n").write("\n".join(L))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
